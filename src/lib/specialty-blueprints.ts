export function cityIn(cSlug: string): string {
  const norm = cSlug.toLowerCase().trim();
  const loc = CITY_LOCATIVE_RU[norm];
  if (loc) return `в ${loc}`;
  return `в г. ${cityLabel(cSlug)}`;
}

export function cityLoc(cSlug: string): string {
  const norm = cSlug.toLowerCase().trim();
  return CITY_LOCATIVE_RU[norm] || cityLabel(cSlug);
}

